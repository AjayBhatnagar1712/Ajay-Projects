public class array_string {
    public static void main(String[] args) {
        String [] name = new String[4];
        name[0] = "Ajay";
        name[1] = "Ajay1";
        name[2] = "Ajay2";
        name[3] = "Ajay3";
        System.out.println(name[3]);

        char [] initials = new char[4];
        initials [0] = 'k';
        initials [1] = 'a';
        initials [2] = 'r';
        initials [3] = 't';
        System.out.println(initials[0]);
    }
}