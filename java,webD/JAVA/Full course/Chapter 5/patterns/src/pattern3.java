public class pattern3 {
    public static void main(String[] args) {
        for (int i = 1 ; i<=4 ; i++){
            for (int j = 1 ; j<=1; j++){
                System.out.println("*****");
            }
            for (int k = 1 ; k<=2 ; k++){
                System.out.println("*   *");
            }
            for (int l = 1 ; l<=1; l++){
                System.out.println("*****");
            }

            System.out.println();
        }
    }
}
