public class operators {
    public static void main(String[] args) {
        int a = 12;
        //arithmetic operator
        a += 3;
        System.out.println(a);
        //comparison operator
        System.out.println(45==23);
        //And operator
        System.out.println(32>31 & 23>1);
        //And operator
        System.out.println(32>31 && 23>1);
        //or operator
        System.out.println(23>11 || 32>33);
    }
}
