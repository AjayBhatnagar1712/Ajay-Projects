export const normalize = value => String(value).replace(/\s+/g, ' ').trim().toLowerCase();
const hindi = new Map(copy.map(([english, translation]) => [normalize(english), translation]));
export function translate(value, language = 'en') {
  return language === 'hi' ? hindi.get(normalize(value)) ?? value : value;
}
export function hasTranslation(value) {
  return hindi.has(normalize(value));
}
