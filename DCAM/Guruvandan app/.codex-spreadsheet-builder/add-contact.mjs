import fs from "node:fs/promises";
import { FileBlob, SpreadsheetFile } from "@oai/artifact-tool";
const path = "D:/DCAM/Guruvandan app/Mehi Awakening/Lynin manufacturer.xlsx";
const wb = await SpreadsheetFile.importXlsx(await FileBlob.load(path));
const sheet = wb.worksheets.getItem("Manufacturers");
if (sheet.getRange("C1").values[0][0] !== "location") throw new Error("Unexpected header");
const n = Math.max(51, sheet.getUsedRange().values.length);
const preview = async (name, range) => {
  const png = await wb.render({sheetName:"Manufacturers", range, scale:1, format:"png"});
  await fs.writeFile(new URL(name, import.meta.url), new Uint8Array(await png.arrayBuffer()));
};
await preview("before.png", "A1:D6");
if (!process.argv.includes("--edit")) process.exit(0);
const old = sheet.tables.items[0];
const name = old.name;
const style = old.style;
old.delete();
sheet.getRange(`E1:E${n}`).copyFrom(sheet.getRange(`D1:D${n}`), "all");
sheet.getRange(`D1:D${n}`).copyFrom(sheet.getRange(`C1:C${n}`), "all");
sheet.getRange(`C1:C${n}`).copyFrom(sheet.getRange(`B1:B${n}`), "all");
sheet.getRange(`C2:C${n}`).clear({applyTo:"contents"});
sheet.getRange("C1").values = [["contact"]];
sheet.getRange(`C2:C${n}`).setNumberFormat("@");
sheet.getRange("C:C").format.columnWidth = 22;
sheet.getRange("D:D").format.columnWidth = 28;
sheet.getRange("E:E").format.columnWidth = 40;
const table = sheet.tables.add(`A1:E${n}`, true, name);
table.style = style;
table.showFilterButton = true;
wb.recalculate();
await preview("after.png", "A1:E6");
await (await SpreadsheetFile.exportXlsx(wb)).save(path);
const saved = await SpreadsheetFile.importXlsx(await FileBlob.load(path));
console.log(JSON.stringify(saved.worksheets.getItem("Manufacturers").getRange("A1:E1").values));
